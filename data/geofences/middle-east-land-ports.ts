// ============================================================================
// TYPE DEFINITIONS
// ============================================================================

export interface LandPortData {
  id: string
  code: string
  name: string
  nameLocal?: string
  alternateNames?: string[]
  country: string
  coordinates: { lat: number; lng: number }
  type: 'BORDER_CROSSING_COMPLEX' | 'BORDER_ENTRY_POINT' | 'BORDER_EXIT_POINT' | 'CUSTOMS_CLEARANCE_FACILITY' | 'DRY_PORT' | 'LOGISTICS_HUB'
  connectedPort?: string // ID of connected port on other side
  distanceToConnected?: number // km
  
  // Operations
  operatingHours: {
    sunday?: { open: string; close: string } | null
    monday?: { open: string; close: string } | null
    tuesday?: { open: string; close: string } | null
    wednesday?: { open: string; close: string } | null
    thursday?: { open: string; close: string } | null
    friday?: { open: string; close: string } | null
    saturday?: { open: string; close: string } | null
    notes?: string
    timezone: string
  }
  
  // Capabilities
  hasCustoms: boolean
  hasImmigration: boolean
  hasQuarantine: boolean
  hasSecurity: boolean
  hasXRayScanning: boolean
  hasWeighbridge: boolean
  hasColdStorage: boolean
  hasDangerousGoodsHandling: boolean
  hasLivestockHandling: boolean
  
  // Processing
  averageProcessingTime: {
    export: number // hours
    import: number // hours
    transit: number // hours
  }
  maxVehicleCapacity?: number // vehicles per day
  
  // Contact
  customsOffice?: string
  phone?: string
  email?: string
  
  // Metadata
  notes?: string
  reliabilityScore?: number // 0-100
  congestionLevel?: 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL'
  
  // Geofence configuration
  geofenceRadius?: number // meters (default: 500m for land ports)
  expectedDwellTime?: number // minutes
  maxDwellTime?: number // minutes
}

